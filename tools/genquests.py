for i, (ic, name, desc, st, label) in enumerate(quests):
    y = top + 40 + i*rowh
    c = colors[st]
    mid = y + rowh/2
    g = [f'<g class="row" style="animation-delay:{0.2*i:.1f}s">']
    if i: g.append(f'<line x1="50" y1="{y}" x2="950" y2="{y}" stroke="#d4af37" stroke-opacity=".12"/>')
    g.append(f'<text x="54" y="{mid+8:.0f}" class="ico">{ic}</text><text x="92" y="{mid+6:.0f}" class="h">{e(name)}</text>')
    dy = mid - (len(desc)-1)*9 + 4
    for j, line in enumerate(desc):
        g.append(f'<text x="340" y="{dy + j*18:.0f}" class="d">{e(line)}</text>')
    g.append(f'<rect x="785" y="{mid-15:.0f}" width="165" height="30" rx="15" fill="{c}" fill-opacity=".12" stroke="{c}" stroke-opacity=".7"/>')
    g.append(f'<circle class="dot" cx="803" cy="{mid:.0f}" r="5" fill="{c}" style="animation-delay:{0.5*i:.1f}s"/>')
    g.append(f'<text x="815" y="{mid+4.5:.0f}" class="st" fill="{c}">{e(label)}</text></g>')
    o.append("".join(g))
o.append('</svg>\n')
open("assets/quests.svg", "w").write("\n".join(o))
