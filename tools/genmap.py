def mountains(x, y, n, color):
    out = []
    for i in range(n):
        mx = x + i*22
        h = 26 + (i % 2)*10
        out.append(f'<path d="M {mx-16} {y} L {mx} {y-h} L {mx+16} {y} Z" fill="{color}" opacity="0.55"/>'
                   f'<path d="M {mx} {y-h} L {mx+5} {y-h+10} L {mx-3} {y-h+8} Z" fill="#f4e9cf" opacity="0.8"/>')
    return "".join(out)

def trees(x, y, n):
    return "".join(f'<path d="M {x+i*14} {y} l -6 0 l 6 -16 l 6 16 z" fill="#4d6b3c" opacity="0.6"/>' for i in range(n))

import random
CURRENT = 3  # index of the stop I am at now (0 = Shire, 1-5 = domains, 6 = exam)
random.seed(7)
def edge(x1,y1,x2,y2,steps,amp,tears):
    pts=[]
    for i in range(steps):
        t=i/steps
        x=x1+(x2-x1)*t; y=y1+(y2-y1)*t
        j=random.uniform(-amp,amp)
        if i in tears: j=tears[i]
        if x1==x2: x+=j
        else: y+=j
        pts.append((x,y))
    return pts
